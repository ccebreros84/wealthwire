// Localises a validation issue or file error. Falls back to the English text
// the validator produced, so a code without a translation never shows blank.
export function issueText(d, issue) {
  if (!issue) return '';
  const fn = issue.code && d.issue[issue.code];
  if (!fn) return issue.message || '';
  const p = { ...(issue.params || {}) };
  if (p.klassKey) p.inferred = d.klass[p.klassKey] || p.klassKey.toLowerCase();
  return fn(p);
}
